name = "Pradeep_Kumar"

print(name[2:5]) #it means from 2 to 4
print(name[:5]) #it means from 0 to 4
print(name[2:]) #it means from 2 to last
print(name[2:len(name)]) #it means from 2 to last

#Let's see the negative indexing
print(name[-3:-1]) #it means that the string will be in negative indexing so it will count from right to left i.e. from r to P
print(name[-5:len(name)])